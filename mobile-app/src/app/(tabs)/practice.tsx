import {
  checkMessage,
  DEFAULT_GENERATED_DRILL_COUNT,
  generateSADrills,
  MESSAGE_CHECK_MAX_LENGTH,
  type CheckMessageResult,
  type DeepSeekErrorReason,
  type GenerateDrillsResult,
  type GeneratedDrill,
} from '@/lib/deepseek';
import type { LanguageCode } from '@/i18n';
import { useAppStore } from '@/store/useAppStore';

type CheckSuccess = Extract<CheckMessageResult, { ok: true }>;
type DailyErrorReason = DeepSeekErrorReason | 'empty';

function errorKey(reason: DailyErrorReason): string {
  switch (reason) {
    case 'missing-key':
      return 'aiErrorMissingKey';
    case 'invalid-input':
      return 'aiErrorInvalidInput';
    case 'invalid-key':
      return 'aiErrorInvalidKey';
    case 'rate-limited':
      return 'aiErrorRateLimited';
    case 'network':
      return 'aiErrorNetwork';
    case 'invalid-response':
      return 'aiErrorInvalidResponse';
    case 'empty':
      return 'aiDrillsNoneReturned';
    default:
      return 'aiErrorUnexpected';
  }
}

export default function PracticeScreen() {
  const { t } = useTranslation();
  const language = (useAppStore((s) => s.language) ?? 'en') as LanguageCode;
  const storedDrillPicks = useAppStore((s) => s.drillPicks);
  const answerStoredDrill = useAppStore((s) => s.answerDrill);

  const [message, setMessage] = useState('');
  const [checking, setChecking] = useState(false);
  const [checkResult, setCheckResult] = useState<CheckSuccess | null>(null);
  const [checkError, setCheckError] = useState<DeepSeekErrorReason | null>(null);
  const checkInFlight = useRef(false);

  // Daily practice: AI-generated by default. If the very first generation attempt fails (or
  // comes back empty), we fall back to the real, sourced drills in drills.ts rather than show
  // nothing — never a blank screen. A later refresh failure keeps whatever is already on screen
  // (stale-while-revalidate) instead of discarding good content.
  const [dailyDrills, setDailyDrills] = useState<GeneratedDrill[] | null>(null);
  const [dailyPicks, setDailyPicks] = useState<Record<number, 'scam' | 'safe'>>({});
  const [dailyLoading, setDailyLoading] = useState(true);
  const [dailyError, setDailyError] = useState<DailyErrorReason | null>(null);
  const [hasLoadedOnce, setHasLoadedOnce] = useState(false);
  const dailyInFlight = useRef(false);
  // Only the most recent request may update the screen, so a slow reply in the old language can
  // never overwrite a newer one after the student switches language.
  const dailyRequestId = useRef(0);

  const trimmedMessage = message.trim();
  const overLimit = message.length > MESSAGE_CHECK_MAX_LENGTH;
  const canSubmit = trimmedMessage.length > 0 && !overLimit;

  async function runCheck() {
    if (checkInFlight.current) return;
    checkInFlight.current = true;
    setChecking(true);
    setCheckError(null);

    const result = await checkMessage(trimmedMessage, language);
    if (result.ok) {
      setCheckResult(result);
      setCheckError(null);
    } else {
      setCheckResult(null);
      setCheckError(result.error);
    }

    setChecking(false);
    checkInFlight.current = false;
  }

  // Applied inside a .then() below, never called synchronously — the effect only ever starts a
  // promise chain, it doesn't call setState itself.
  function applyDailyResult(result: GenerateDrillsResult) {
    if (result.ok && result.drills.length > 0) {
      setDailyDrills(result.drills);
      setDailyPicks({});
      setDailyError(null);
    } else {
      setDailyError(result.ok ? 'empty' : result.error);
    }
    setDailyLoading(false);
    setHasLoadedOnce(true);
    dailyInFlight.current = false;
  }

  // The user-facing entry point (button press): opts the loading/error state in immediately,
  // then applies the eventual result once the request resolves.
  function requestDailyDrills() {
    const requestId = ++dailyRequestId.current;
    dailyInFlight.current = true;
    void generateSADrills(DEFAULT_GENERATED_DRILL_COUNT, language).then((result) => {
      if (requestId === dailyRequestId.current) applyDailyResult(result);
    });
  }

  function refreshDailyDrills() {
    if (dailyInFlight.current) return;
    setDailyLoading(true);
    setDailyError(null);
    requestDailyDrills();
  }

  // Runs on first load and again whenever the student switches language, so the practice
  // messages are always in the language the rest of the app is in.
  useEffect(() => {
    requestDailyDrills();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [language]);

  const showSkeleton = !hasLoadedOnce && dailyLoading;
  const isFallback = dailyDrills === null && hasLoadedOnce;
  const displayDrills: (Drill | GeneratedDrill)[] | null = dailyDrills ?? (isFallback ? getDrills(language) : null);

  return (
    <SafeAreaView style={styles.screen} edges={['top']}>
      <ScrollView contentContainerStyle={styles.content} showsVerticalScrollIndicator={false}>
        <View style={styles.header}>
          <Text style={styles.title}>{t('practice')}</Text>
          <Text style={styles.subtitle}>{t('practiceSubtitle')}</Text>
          <View style={styles.rule} />
        </View>

        {showSkeleton && <DailySkeleton />}

        {!showSkeleton && isFallback && <Text style={styles.fallbackNote}>{t('dailyPracticeFallbackNote')}</Text>}

        {!showSkeleton && dailyDrills && <Text style={styles.aiKicker}>{t('aiDrillsLabel')}</Text>}

        {!showSkeleton &&
          displayDrills?.map((drill, i) => {
            const pick = isFallback ? storedDrillPicks[i] : dailyPicks[i];
            const answered = pick !== undefined;
            const right = answered && (pick === 'scam') === drill.isScam;
            return (
              <DrillCard
                key={i}
                drill={drill}
                pick={pick}
                answered={answered}
                right={right}
                onPick={(choice) => {
                  if (isFallback) {
                    answerStoredDrill(i, choice);
                  } else if (dailyPicks[i] === undefined) {
                    setDailyPicks((prev) => ({ ...prev, [i]: choice }));
                  }
                }}
                t={t}
              />
            );
          })}

        {!showSkeleton && (
          <View style={styles.dailyActions}>
            <PrimaryButton
              label={dailyLoading ? t('generatingDrills') : t('getNewExamples')}
              variant="secondary"
              disabled={dailyLoading}
              onPress={refreshDailyDrills}
            />
            {dailyLoading && (
              <View style={styles.loadingRow} testID="daily-drills-refreshing">
                <ActivityIndicator color={Colors.accent} />
                <Text style={styles.loadingText}>{t('generatingDrills')}</Text>
              </View>
            )}
            {!dailyLoading && dailyError && dailyDrills && <Text style={styles.errorText}>{t(errorKey(dailyError))}</Text>}
          </View>
        )}

        <View style={styles.aiSection}>
          <Text style={styles.aiKicker}>{t('aiTutor')}</Text>
          <View style={[styles.inputRow, overLimit && styles.inputRowError]}>
            <Icon name="chatbox-ellipses-outline" size={18} color={Colors.textMuted} />
            <TextInput
              placeholder={t('messageCheckPlaceholder')}
              placeholderTextColor={Colors.textMuted}
              style={styles.input}
              multiline
              value={message}
              onChangeText={(text) => {
                setMessage(text);
                setCheckResult(null);
                setCheckError(null);
              }}
            />
          </View>
          <View style={styles.counterRow}>
            {overLimit && <Text style={styles.errorText}>{t('messageTooLong')}</Text>}
            <Text style={[styles.counter, overLimit && styles.counterError]}>
              {t('charactersCount', { count: message.length, max: MESSAGE_CHECK_MAX_LENGTH })}
            </Text>
          </View>

          <PrimaryButton
            label={checking ? t('checkingMessage') : t('checkMessage')}
            variant="secondary"
            disabled={!canSubmit || checking}
            onPress={runCheck}
          />

          {checking && (
            <View style={styles.loadingRow} testID="message-check-loading">
              <ActivityIndicator color={Colors.accent} />
              <Text style={styles.loadingText}>{t('checkingMessage')}</Text>
            </View>
          )}

          {!checking && checkError && (
            <View style={styles.errorCard}>
              <Text style={styles.errorText}>{t(errorKey(checkError))}</Text>
              <Pressable onPress={runCheck} style={styles.retryButton} hitSlop={8}>
                <Text style={styles.retryText}>{t('tryAgain')}</Text>
              </Pressable>
            </View>
          )}

          {!checking && checkResult && (
            <View style={styles.resultCard}>
              <Text style={styles.verdict}>{t(`verdict${capitalize(checkResult.verdict)}`)}</Text>
              <Text style={styles.confidence}>
                {t('confidenceLabel')}: {t(`confidence${capitalize(checkResult.confidence)}`)}
              </Text>
              <Text style={styles.redFlagsHeading}>
                {checkResult.redFlags.length > 0 ? t('redFlagsFound') : t('noRedFlagsFound')}
              </Text>
              {checkResult.redFlags.map((flag, i) => (
                <Text key={i} style={styles.redFlag}>
                  • {flag}
                </Text>
              ))}
              <Text style={styles.explanation}>{checkResult.explanation}</Text>
            </View>
          )}
        </View>
      </ScrollView>
    </SafeAreaView>
  );
}

function DailySkeleton() {
  return (
    <View style={styles.skeletonWrap} testID="daily-drills-skeleton">
      {[0, 1, 2].map((i) => (
        <View key={i} style={styles.skeletonCard}>
          <View style={styles.skeletonLine} />
          <View style={[styles.skeletonLine, { width: '70%' }]} />
        </View>
      ))}
    </View>
  );
}

function capitalize<T extends string>(value: T): string {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

function DrillCard({
  drill,
  pick,
  answered,
  right,
  onPick,
  t,
}: {
  drill: Drill | GeneratedDrill;
  pick: 'scam' | 'safe' | undefined;
  answered: boolean;
  right: boolean;
  onPick: (choice: 'scam' | 'safe') => void;
  t: (key: string) => string;
}) {
  return (
    <View style={styles.drillCard}>
      <View style={styles.drillHeaderRow}>
        <Text style={styles.channel}>{drill.channel}</Text>
        <Text style={styles.from}>{drill.from}</Text>
      </View>
      <Text style={styles.body}>{drill.body}</Text>
      <View style={styles.choiceRow}>
        <DrillChoice
          label={t('scam')}
          active={pick === 'scam'}
          correct={answered && pick === 'scam' && right}
          wrong={answered && pick === 'scam' && !right}
          onPress={() => onPick('scam')}
        />
        <DrillChoice
          label={t('legit')}
          active={pick === 'safe'}
          correct={answered && pick === 'safe' && right}
          wrong={answered && pick === 'safe' && !right}
          onPress={() => onPick('safe')}
        />
      </View>
      {answered && (
        <Text style={styles.explain}>
          <Text style={styles.explainBold}>{right ? t('correct') : t('notQuite')}. </Text>
          {drill.explain}
        </Text>
      )}
    </View>
  );
}

function DrillChoice({
  label,
  active,
  correct,
  wrong,
  onPress,
}: {
  label: string;
  active: boolean;
  correct: boolean;
  wrong: boolean;
  onPress: () => void;
}) {
  return (
    <Pressable
      onPress={onPress}
      style={[
        styles.choiceButton,
        correct && { backgroundColor: Colors.accent, borderColor: Colors.accent },
        wrong && { backgroundColor: Colors.neutral300, borderColor: Colors.neutral300 },
      ]}>
      <Text style={[styles.choiceText, (correct || wrong) && { color: correct ? Colors.accentContrast : Colors.text }]}>
        {label}
      </Text>
    </Pressable>
  );
}

